#!/usr/bin/env python3
"""Regenerate python/requirements.lock from python/requirements.txt.

For every pinned package the lock lists the SHA-256 of every wheel that PyPI
serves for that exact version, so pip accepts the right wheel on any CPU and
Python version, and rejects any file that is not one of them.
Run it only when the pins change, then test the install before releasing.
"""
import json
import os
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "python", "requirements.txt")
OUT = os.path.join(HERE, "..", "python", "requirements.lock")

# Needed by pyOpenSSL on Python older than 3.13 only.
EXTRA = [("typing-extensions", "4.16.0", 'python_version < "3.13"')]


def wheels(name, version):
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as res:
        data = json.load(res)
    return sorted({f["digests"]["sha256"] for f in data["urls"] if f["packagetype"] == "bdist_wheel"})


def main():
    pins = []
    with open(SRC, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith("#"):
                name, version = line.split("==")
                pins.append((name, version, None))
    pins += EXTRA
    out = [
        "# Generated by scripts/make-lock.py from requirements.txt. Do not edit by hand.",
        "# Every wheel PyPI serves for each pinned version, by SHA-256.",
    ]
    for name, version, marker in pins:
        hashes = wheels(name, version)
        if not hashes:
            raise SystemExit(f"{name}=={version}: no wheels on PyPI")
        head = f"{name}=={version}" + (f" ; {marker}" if marker else "")
        out.append(head + " \\")
        out += [f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "") for i, h in enumerate(hashes)]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {len(pins)} packages")


if __name__ == "__main__":
    main()
